/// Minimal runtime i18n — returns `&'static str` for every key so results
/// can be passed directly to GTK widget builders.
///
/// English is the default; each additional language is a match arm in its own
/// function.  Unknown keys fall back to the English string (the key itself).
use std::cell::Cell;

#[derive(Clone, Copy, PartialEq, Default)]
pub enum Lang {
    #[default]
    En,
    Es,
    Pt,
    Fr,
    De,
    Ru,
    Zh,
    Tr,
    Sv,
    Ja,
    Hi,
    It,
    Pl,
    Id,
    No,
    Ar,
    Ro,
    Fi,
    Af,
    Ga,
}

impl Lang {
    pub fn from_code(code: &str) -> Self {
        match code {
            "es" => Self::Es,
            "pt" => Self::Pt,
            "fr" => Self::Fr,
            "de" => Self::De,
            "ru" => Self::Ru,
            "zh" => Self::Zh,
            "tr" => Self::Tr,
            "sv" => Self::Sv,
            "ja" => Self::Ja,
            "hi" => Self::Hi,
            "it" => Self::It,
            "pl" => Self::Pl,
            "id" => Self::Id,
            "no" => Self::No,
            "ar" => Self::Ar,
            "ro" => Self::Ro,
            "fi" => Self::Fi,
            "af" => Self::Af,
            "ga" => Self::Ga,
            _    => Self::En,
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::Es => "es",
            Self::Pt => "pt",
            Self::Fr => "fr",
            Self::De => "de",
            Self::Ru => "ru",
            Self::Zh => "zh",
            Self::Tr => "tr",
            Self::Sv => "sv",
            Self::Ja => "ja",
            Self::Hi => "hi",
            Self::It => "it",
            Self::Pl => "pl",
            Self::Id => "id",
            Self::No => "no",
            Self::Ar => "ar",
            Self::Ro => "ro",
            Self::Fi => "fi",
            Self::Af => "af",
            Self::Ga => "ga",
        }
    }
}

thread_local! {
    static LANG: Cell<Lang> = Cell::new(Lang::En);
}

pub fn set(lang: Lang) {
    LANG.with(|l| l.set(lang));
}

pub fn current() -> Lang {
    LANG.with(|l| l.get())
}

/// Translate `key` (which is the English string) into the current language.
/// Falls back to the key itself when a translation is missing.
pub fn t(key: &'static str) -> &'static str {
    match current() {
        Lang::En => key,
        Lang::Es => es(key).unwrap_or(key),
        Lang::Pt => pt(key).unwrap_or(key),
        Lang::Fr => fr(key).unwrap_or(key),
        Lang::De => de(key).unwrap_or(key),
        Lang::Ru => ru(key).unwrap_or(key),
        Lang::Zh => zh(key).unwrap_or(key),
        Lang::Tr => tr(key).unwrap_or(key),
        Lang::Sv => sv(key).unwrap_or(key),
        Lang::Ja => ja(key).unwrap_or(key),
        Lang::Hi => hi(key).unwrap_or(key),
        Lang::It => it(key).unwrap_or(key),
        Lang::Pl => pl(key).unwrap_or(key),
        Lang::Id => id(key).unwrap_or(key),
        Lang::No => no(key).unwrap_or(key),
        Lang::Ar => ar(key).unwrap_or(key),
        Lang::Ro => ro(key).unwrap_or(key),
        Lang::Fi => fi(key).unwrap_or(key),
        Lang::Af => af(key).unwrap_or(key),
        Lang::Ga => ga(key).unwrap_or(key),
    }
}

/// Returns true for RTL languages (currently only Arabic).
pub fn is_rtl() -> bool {
    current() == Lang::Ar
}

